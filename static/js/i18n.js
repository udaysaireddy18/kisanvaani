let currentLang = "hi";

function i18nGetLang() {
  let saved = "hi";
  try {
    saved = localStorage.getItem(I18N_STORAGE_KEY) || "hi";
  } catch (error) {
    // localStorage may be unavailable in private browsing; ignore.
  }
  return I18N_LANGS.includes(saved) ? saved : "hi";
}

function i18nSetLang(lang) {
  currentLang = I18N_LANGS.includes(lang) ? lang : "en";
  try {
    localStorage.setItem(I18N_STORAGE_KEY, currentLang);
  } catch (error) {
    // Ignore storage failures; translation still works for this page load.
  }
  applyTranslations();
  return currentLang;
}

function t(key, vars) {
  let text = I18N[currentLang]?.[key];
  if (text === undefined) text = I18N.en[key];
  if (text === undefined) return key;
  if (vars) {
    Object.keys(vars).forEach((name) => {
      text = text.replace(new RegExp("\\{" + name + "\\}", "g"), String(vars[name]));
    });
  }
  return text;
}

function applyTranslations() {
  document.documentElement.lang = currentLang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
}
